def lexical(surface):
 out=[]
 for w in re.findall('[a-z]+',surface.lower()):
  w={'fell':'fall','fallen':'fall','made':'make','shot':'shoot','drove':'drive','beaten':'beat'}.get(w,w)
  for suffix in ('ing','ed','es','s'):
   if w.endswith(suffix) and len(w)>len(suffix)+2:
    w=w[:-len(suffix)]
    if len(w)>2 and w[-1:]==w[-2:-1]:w=w[:-1]
    break
  if w.endswith('e') and len(w)>3:w=w[:-1]
  out.append(w)
 return set(out)

def alternatives(bundle,row):
 r,c=row['root'],row['extraction']['certificate'];d=bundle['documents'][r['doc']]
 source=d['mentions'][c['cause']];a=lexical(source['surface']);scores={tuple(x['pair']):x for x in bundle['scores'][r['doc']]};found=[]
 for mid,m in d['mentions'].items():
  if mid in (c['cause'],c['effect']):continue
  b=lexical(m['surface']);overlap=len(a&b)/max(1,len(a|b));target=tuple(sorted([mid,c['effect']]))
  if overlap<.5 or target not in scores or scores[target]['fusion']>=.39:continue
  found.append((-overlap,abs(source['sentence']-m['sentence']),mid))
 return [m for _,_,m in sorted(found)[:2]]

